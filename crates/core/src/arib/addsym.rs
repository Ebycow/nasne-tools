//! ARIB STD-B24 の追加記号・追加漢字（漢字系集合の 85・86 区と 90〜94 区）
//!
//! 各区の表は「最初の点」から 1 点ずつ順に並べる。"" は何も表示しない符号。
//! BMP 外の文字は \u{...} で書く。

/// 区 → (最初の点, その区の文字)
const ROWS: &[(u8, u8, &[&str])] = &[
    (0x75, 0x21, KU85),
    (0x76, 0x21, KU86),
    (0x7A, 0x50, KU90),
    (0x7C, 0x21, KU92),
    (0x7D, 0x21, KU93),
    (0x7E, 0x21, KU94),
];

/// 追加記号・追加漢字なら Some（"" は何も表示しない）、表にない符号なら None
pub fn get(ku: u8, ten: u8) -> Option<&'static str> {
    let &(_, first, row) = ROWS.iter().find(|r| r.0 == ku)?;
    row.get(ten.checked_sub(first)? as usize).copied()
}

